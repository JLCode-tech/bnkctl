package state

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// State holds the IDs cache (state.env) for a single cluster.
type State struct {
	dir      string
	data     map[string]string
	readOnly bool
}

// New creates or loads a State for dir.
func New(dir string) (*State, error) {
	return Load(dir)
}

// Load reads state.env from dir. If the file does not exist yet, an empty State
// is returned with no error.
func Load(dir string) (*State, error) {
	if filepath.Base(dir) == "state.env" {
		dir = filepath.Dir(dir)
	}
	s := &State{
		dir:  dir,
		data: make(map[string]string),
	}

	path := s.path()
	// #nosec G304 -- state.env inside operator workspace directory
	f, err := os.Open(path)
	if os.IsNotExist(err) {
		return s, nil
	}
	if err != nil {
		return nil, fmt.Errorf("opening %s: %w", path, err)
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		s.data[strings.TrimSpace(k)] = strings.TrimSpace(v)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	return s, nil
}

// Get returns the value for key, or "" if not set.
func (s *State) Get(key string) string {
	if s == nil {
		return ""
	}
	return s.data[key]
}

// All returns a copy of all key-value pairs in state.
func (s *State) All() map[string]string {
	if s == nil {
		return map[string]string{}
	}
	out := make(map[string]string, len(s.data))
	for k, v := range s.data {
		out[k] = v
	}
	return out
}

// Set records key=value in memory. Call Save to persist to disk.
func (s *State) Set(key, value string) {
	if s == nil {
		return
	}
	if s.data == nil {
		s.data = make(map[string]string)
	}
	s.data[key] = value
}

// Delete removes key from the state. Call Save to persist.
func (s *State) Delete(key string) {
	if s == nil {
		return
	}
	delete(s.data, key)
}

// MarkReadOnly puts the State into read-only mode for dry-run.
func (s *State) MarkReadOnly() {
	if s != nil {
		s.readOnly = true
	}
}

// IsReadOnly reports whether Save is currently suppressed.
func (s *State) IsReadOnly() bool {
	if s == nil {
		return true
	}
	return s.readOnly
}

// Save writes the in-memory state to state.env atomically.
func (s *State) Save() error {
	if s == nil || s.readOnly {
		return nil
	}
	if err := os.MkdirAll(s.dir, 0o750); err != nil {
		return fmt.Errorf("creating state dir %s: %w", s.dir, err)
	}

	tmp := s.path() + ".tmp"
	// #nosec G304 -- temporary state.env inside operator workspace directory
	f, err := os.Create(tmp)
	if err != nil {
		return fmt.Errorf("creating temp state: %w", err)
	}

	fmt.Fprintf(f, "# Generated by bnkctl on %s — do not edit by hand\n",
		time.Now().UTC().Format(time.RFC3339))
	keys := make([]string, 0, len(s.data))
	for k := range s.data {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(f, "%s=%s\n", k, s.data[k])
	}

	if err := f.Close(); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("closing temp state: %w", err)
	}
	if err := os.Rename(tmp, s.path()); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("renaming state to %s: %w", s.path(), err)
	}
	return nil
}

func (s *State) path() string {
	return filepath.Join(s.dir, "state.env")
}

// Path returns the path to state.env, or "" if the state directory is unset.
func (s *State) Path() string {
	if s == nil || s.dir == "" {
		return ""
	}
	return s.path()
}

// Dir returns the state directory.
func (s *State) Dir() string {
	if s == nil {
		return ""
	}
	return s.dir
}

// KubeconfigPath returns the path where kubeconfig is saved for this cluster.
// If KUBECONFIG_PATH or KUBECONFIG is set in state, it is returned when it
// exists on disk; otherwise, when a relative path does not exist from the
// current working directory or when filepath.Join(s.dir, "kubeconfig") exists
// on disk, it falls back to filepath.Join(s.dir, "kubeconfig").
func (s *State) KubeconfigPath() string {
	if s == nil {
		return ""
	}
	fallback := ""
	if s.dir != "" {
		fallback = filepath.Join(s.dir, "kubeconfig")
	}
	var firstCustom string
	for _, key := range []string{"KUBECONFIG_PATH", "KUBECONFIG"} {
		custom := s.Get(key)
		if custom == "" {
			continue
		}
		if firstCustom == "" {
			firstCustom = custom
		}
		if _, err := os.Stat(custom); err == nil {
			return custom
		}
	}
	if firstCustom != "" {
		if fallback != "" {
			if _, err := os.Stat(fallback); err == nil || !filepath.IsAbs(firstCustom) {
				return fallback
			}
		}
		return firstCustom
	}
	return fallback
}

// WriteValues loads state.env from dir (or starts empty if missing), merges kv,
// and saves atomically.
func WriteValues(dir string, kv map[string]string) error {
	st, err := Load(dir)
	if err != nil {
		return err
	}
	for k, v := range kv {
		st.Set(k, v)
	}
	return st.Save()
}
